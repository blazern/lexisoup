                        if (continuation.isActive) {
                            if (finished) {
                                continuation.resume(Unit.right())
                            } else {
                                continuation.resume(Err("Seek to start was interrupted").left())
                            }
                        }
                    }
                } catch (e: Exception) {
                    if (continuation.isActive) {
                        continuation.resume(Err.from(e).left())
                    }
                }
            }
        }
