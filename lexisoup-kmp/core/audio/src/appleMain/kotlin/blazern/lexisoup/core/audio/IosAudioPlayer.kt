                                Err("AVAsset loading was cancelled: $url").left()
                            }
                            else -> {
                                Err("AVAsset did not become playable: $url").left()
                            }
                        }

                        if (continuation.isActive) {
                            continuation.resume(result)
                        }
                    }
                }
            } catch (e: Exception) {
                if (continuation.isActive) {
                    continuation.resume(Err.from(e).left())
                }
            }
